// The compatibility kit's feature files: one per sample of the installed kit, written to
// `compatibility/<sample>.feature` (as e2e's are `e2e/*.feature`) by `pnpm compatibility:generate`
// (this module, run by Node), and committed: run it after a kit update, or a change to `./known.ts`
// (a unit test checks every sample's file is the one written here: `./__tests__/features.test.ts`). Each is a Scenario
// Outline with a row per mode, run by e2e's harness (`../steps/compatibility.ts`); a known
// difference's mode its own `@knownFailure` example, a sample left out `@leftOut` (`./known.ts`).
// Generated: edit `./known.ts` or this file, not them.
import { readdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { samples } from "./kit.ts";
import {
  knownFailures,
  leftOut,
  leftOutModes,
  type Mode,
  modes,
} from "./known.ts";

/** The generated feature files' folder: `compatibility/`. */
export const featuresDir = path.join(import.meta.dirname, "..");

/** An Examples table of `rows`' modes, with its tags and name (its column as wide as its widest cell). */
const examples = (rows: readonly Mode[], header: string) => {
  const width = Math.max("mode".length, ...rows.map((mode) => mode.length));
  return [
    `    ${header}`,
    `      | ${"mode".padEnd(width)} |`,
    ...rows.map((mode) => `      | ${mode.padEnd(width)} |`),
  ].join("\n");
};

/** A sample's feature file. */
export const featureOf = (sample: string) => {
  const reason = leftOut[sample];
  const known = knownFailures[sample] ?? {};
  const outOf = leftOutModes[sample] ?? {};
  const run = modes.filter((mode) => !outOf[mode]);
  const expected = run.filter((mode) => !known[mode]);
  // One example per known difference: its reason its name, as the report shows it.
  const failures = run.flatMap((mode) => {
    const why = known[mode];
    return why ? [examples([mode], `@knownFailure\n    Examples: ${why}`)] : [];
  });
  return [
    "# Generated by compatibility/utils/generate.ts: edit compatibility/utils/known.ts, not this file.",
    ...(reason ? ["@leftOut"] : []),
    `Feature: Compatibility: ${sample}`,
    `  Cucumber's compatibility kit sample \`${sample}\`: the plugin reports what cucumber does.`,
    ...(reason ? [`  Left out: ${reason}.`] : []),
    ...Object.entries(outOf).map(
      ([mode, why]) => `  Not in ${mode} mode: ${why}.`,
    ),
    "",
    "  Scenario Outline: The plugin reports what cucumber does (<mode>)",
    `    Given the compatibility kit's sample "${sample}"`,
    "    When I run it with cucumber, and with vitest in <mode> mode",
    "    Then vitest reports what cucumber does",
    "    And its messages are cucumber's",
    "",
    ...[
      ...(expected.length > 0 ? [examples(expected, "Examples:")] : []),
      ...failures,
    ].flatMap((table) => [table, ""]),
  ].join("\n");
};

/** Writes a feature file per sample of the installed kit (and only those: earlier ones removed). */
const writeCompatibilityFeatures = () => {
  const kitSamples = samples();
  for (const file of readdirSync(featuresDir)) {
    if (
      file.endsWith(".feature") &&
      !kitSamples.includes(file.replace(/\.feature$/, ""))
    ) {
      rmSync(path.join(featuresDir, file));
    }
  }
  for (const sample of kitSamples) {
    writeFileSync(
      path.join(featuresDir, `${sample}.feature`),
      featureOf(sample),
    );
  }
};

// `pnpm compatibility:generate`.
// eslint-disable-next-line n/no-unsupported-features/node-builtins -- a dev script, on Node 24.2+.
if (import.meta.main) {
  writeCompatibilityFeatures();
}
